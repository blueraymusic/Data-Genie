"""Real PostgreSQL checks: GENIE_TEST_POSTGRES=1 .venv/bin/python -m unittest tests.test_postgres_integration."""

import os
from pathlib import Path
import shutil
import secrets
import socket
import subprocess
import tempfile
import time
import unittest
import uuid
from unittest.mock import patch

import authentication
import workbench


@unittest.skipUnless(os.environ.get("GENIE_TEST_POSTGRES") == "1", "Opt in to the disposable PostgreSQL integration suite")
class PostgresIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import psycopg
        cls.psycopg = psycopg
        cls.cluster = tempfile.TemporaryDirectory(prefix="genie-postgres-tests-")
        root = Path(cls.cluster.name)
        cls.password = secrets.token_urlsafe(32)
        password_file = root / "init-password"
        password_file.write_text(cls.password)
        password_file.chmod(0o600)
        cls.log = (root / "postgres.log").open("w+")
        with socket.socket() as sock:
            sock.bind(("127.0.0.1", 0))
            cls.port = sock.getsockname()[1]
        subprocess.run([shutil.which("initdb"), "-D", str(root / "data"), "--auth-local=trust", "--auth-host=scram-sha-256", "--pwfile", str(password_file), "-U", "genie_test", "--no-locale", "--encoding=UTF8"], check=True, stdout=cls.log, stderr=cls.log)
        cls.process = subprocess.Popen([shutil.which("postgres"), "-D", str(root / "data"), "-h", "127.0.0.1", "-p", str(cls.port), "-k", str(root)], stdout=cls.log, stderr=cls.log)
        cls.url = f"postgresql://genie_test:{cls.password}@127.0.0.1:{cls.port}/postgres"
        for _ in range(100):
            try:
                with psycopg.connect(cls.url):
                    return
            except psycopg.OperationalError:
                time.sleep(0.05)
        cls.process.terminate()
        cls.process.wait(timeout=5)
        raise RuntimeError("The temporary PostgreSQL cluster did not start.")

    @classmethod
    def tearDownClass(cls):
        cls.process.terminate()
        cls.process.wait(timeout=10)
        cls.log.close()
        cls.cluster.cleanup()

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="genie-postgres-repository-")
        self.previous_repository = workbench.REPOSITORY_PATH
        workbench.REPOSITORY_PATH = Path(self.temporary.name) / "repository.sqlite3"
        self.schema = "test_" + uuid.uuid4().hex
        with self.psycopg.connect(self.url) as connection:
            connection.execute('CREATE SCHEMA "' + self.schema + '"')
            connection.execute(f'CREATE TABLE "{self.schema}".customers(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,state TEXT,amount NUMERIC(10,2),created DATE DEFAULT CURRENT_DATE)')
            connection.execute(f'CREATE TABLE "{self.schema}".orders(id INTEGER PRIMARY KEY,customer_id INTEGER REFERENCES "{self.schema}".customers(id))')
            connection.execute(f'INSERT INTO "{self.schema}".customers(name,state,amount) VALUES (%s,%s,%s),(%s,%s,%s)', ('Sample Iowa','Iowa','12.34','Sample Missouri','Missouri','99.99'))
        self.account = authentication.Accounts(workbench.get_repository()).register("Postgres", "Tester", "pg@example.test", "fixture password long enough")
        self.payload = {"connection_url": self.url, "schema_name": self.schema, "database_name": "Test PostgreSQL"}

    def tearDown(self):
        workbench.REPOSITORY_PATH = self.previous_repository
        with self.psycopg.connect(self.url) as connection:
            connection.execute('DROP SCHEMA "' + self.schema + '" CASCADE')
        self.temporary.cleanup()

    def open(self, changes=False):
        return workbench.start_postgres_session(self.account["account_id"], {**self.payload, "allow_changes": changes})

    def test_schema_reads_metadata_followups_and_saved_credentials(self):
        test = workbench.test_postgres_connection(self.payload)
        self.assertEqual(test["tables"], ["customers", "orders"])
        session = self.open()
        self.assertTrue(session["read_only"])
        self.assertNotIn(self.password, str(session))
        self.assertNotIn(self.password.encode(), Path(workbench.REPOSITORY_PATH).read_bytes())
        session_id = session["session_id"]
        first = workbench.submit_request(session_id, 'show customers where state="Iowa"')
        self.assertTrue(first["matched"], first)
        self.assertEqual(first["rows"][0]["amount"], "12.34")
        followup = workbench.submit_request(session_id, "how many are there?", selected_table="customers")
        self.assertEqual(followup["rows"], [{"row_count": 1}])
        columns = workbench.submit_request(session_id, 'show columns from "customers"')
        self.assertEqual(columns["rows"][0]["name"], "id")
        self.assertEqual(workbench.submit_request(session_id, "how many tables do I have and what are their names")["table_count"], 2)
        structure = workbench.schema_for_session(session_id)["tables"]
        self.assertEqual(structure[1]["foreign_keys"][0]["referenced_table_name"], "customers")
        workbench.end_session(session_id)
        reopened = workbench.resume_session(session_id)
        self.assertNotEqual(reopened["session_id"], session_id)
        self.assertEqual(reopened["connection_id"], session["connection_id"])

    def test_writes_wait_for_confirmation_and_declines_leave_remote_rows_unchanged(self):
        session_id = self.open(changes=True)["session_id"]
        pending = workbench.submit_request(session_id, "INSERT INTO customers(name,state) VALUES ('New sample','Kansas')", raw_sql=True)
        self.assertTrue(pending["requires_confirmation"], pending)
        self.assertEqual(len(workbench.submit_request(session_id, "show customers")["rows"]), 2)
        workbench.confirm_command(session_id, pending["command_id"], pending["confirmation_token"])
        self.assertEqual(len(workbench.submit_request(session_id, "show customers")["rows"]), 3)
        removed = workbench.submit_request(session_id, "DELETE FROM customers", raw_sql=True)
        workbench.decline_command(session_id, removed["command_id"], removed["confirmation_token"])
        self.assertEqual(len(workbench.submit_request(session_id, "show customers")["rows"]), 3)

    def test_read_only_is_enforced_and_ddl_updates_the_schema_after_confirmation(self):
        session_id = self.open()["session_id"]
        rejected = workbench.submit_request(session_id, "DELETE FROM customers", raw_sql=True)
        self.assertFalse(rejected["matched"])
        self.assertIn("read-only", rejected["message"])
        unsupported = workbench.submit_request(session_id, "(SELECT * FROM customers)", raw_sql=True)
        self.assertFalse(unsupported["matched"])
        self.assertEqual(workbench.get_repository().get_request(unsupported["request_id"])["status"], "rejected")
        editable = self.open(changes=True)["session_id"]
        pending = workbench.submit_request(editable, "ALTER TABLE customers ADD COLUMN phone TEXT", raw_sql=True)
        self.assertTrue(pending["requires_confirmation"], pending)
        workbench.confirm_command(editable, pending["command_id"], pending["confirmation_token"])
        with workbench.session_scope(editable):
            self.assertIn("phone", [column["name"] for column in workbench.table_schema("customers")["columns"]])

    def test_pagination_and_connection_ownership(self):
        session = self.open()
        session_id = session["session_id"]
        result = workbench.submit_request(session_id, "SELECT * FROM customers", raw_sql=True)
        self.assertEqual(workbench.result_page(session_id,result["command_id"],1)["rows"][0]["name"], "Sample Missouri")
        other = authentication.Accounts(workbench.get_repository()).register("Other", "Tester", "other@example.test", "another long fixture password")
        with self.assertRaises(ValueError):
            workbench.get_repository().external_connection(session["connection_id"],other["account_id"])

    def test_percent_filters_followups_and_server_row_limits(self):
        session_id = self.open()["session_id"]
        result = workbench.submit_request(session_id,"SELECT * FROM customers WHERE name LIKE 'Sample%' ORDER BY id",raw_sql=True)
        self.assertTrue(result["matched"],result)
        self.assertIn("LIMIT 501",result["executed_sql"])
        page = workbench.result_page(session_id,result["command_id"],1)
        self.assertEqual(page["rows"][0]["name"],"Sample Missouri")
        followup = workbench.submit_request(session_id,"how many are there?", selected_table="customers")
        self.assertEqual(followup["rows"],[{"row_count":2}])

    def test_create_insert_batch_and_rename_preserve_history_and_confirmation(self):
        session_id = self.open(changes=True)["session_id"]
        plans = [{"sql": "CREATE TABLE notes(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,body TEXT)", "summary": "Create notes.", "visualization": "table"},
                 {"sql": "INSERT INTO notes(body) VALUES ('Sample note')", "summary": "Add a sample note.", "visualization": "table"}]
        with patch.object(workbench.gemini_provider, 'generate_plans', return_value=plans):
            pending = workbench.submit_request(session_id, "create notes and add a sample note", interpreter="gemini")
        self.assertTrue(pending["matched"], pending)
        with workbench.session_scope(session_id):
            self.assertNotIn("notes", workbench.visible_tables())
        for command in pending["commands"]:
            workbench.confirm_command(session_id, command["command_id"], command["confirmation_token"])
        self.assertEqual(workbench.submit_request(session_id, "show notes")["rows"][0]["body"], "Sample note")
        renamed = workbench.submit_request(session_id, "ALTER TABLE notes RENAME TO messages", raw_sql=True)
        self.assertTrue(renamed["requires_confirmation"], renamed)
        workbench.confirm_command(session_id, renamed["command_id"], renamed["confirmation_token"])
        self.assertEqual(len(workbench.submit_request(session_id,"show messages")["rows"]),1)
        drop = workbench.submit_request(session_id,"DROP TABLE messages",raw_sql=True)
        self.assertTrue(drop["requires_confirmation"],drop)
        self.assertEqual(drop["preview"]["table"],"messages")
        workbench.confirm_command(session_id,drop["command_id"],drop["confirmation_token"])
        with workbench.session_scope(session_id):
            self.assertNotIn("messages",workbench.visible_tables())

    def test_function_and_cte_scopes_are_enforced_by_the_executed_query(self):
        from psycopg import sql
        with self.psycopg.connect(self.url) as connection:
            connection.execute(sql.SQL("CREATE FUNCTION {}.lower(integer) RETURNS text LANGUAGE sql STABLE AS $$ SELECT 'synthetic shadow result' $$").format(sql.Identifier(self.schema)))
        session_id = self.open()["session_id"]
        qualified = workbench.submit_request(session_id, f'SELECT "{self.schema}".lower(id) FROM customers',raw_sql=True)
        self.assertFalse(qualified["matched"])
        shadowed = workbench.submit_request(session_id,"SELECT lower(id) FROM customers",raw_sql=True)
        self.assertFalse(shadowed["matched"])
        legitimate = workbench.submit_request(session_id,"SELECT pg_catalog.lower(name) AS name FROM CUSTOMERS WHERE EXISTS (SELECT 1 FROM customers)",raw_sql=True)
        self.assertTrue(legitimate["matched"],legitimate)
        self.assertEqual(legitimate["rows"][0]["name"],"sample iowa")
        self.assertIn(self.schema, legitimate["executed_sql"])
        hidden = workbench.submit_request(session_id,"SELECT nspname,(WITH pg_namespace AS (SELECT * FROM customers) SELECT COUNT(*) FROM pg_namespace) FROM pg_namespace",raw_sql=True)
        self.assertFalse(hidden["matched"])

    def test_database_privileges_still_apply_when_app_changes_are_enabled(self):
        from psycopg import sql
        role = "reader_" + uuid.uuid4().hex
        password = secrets.token_urlsafe(24)
        try:
            with self.psycopg.connect(self.url) as connection:
                connection.execute(sql.SQL("CREATE ROLE {} LOGIN PASSWORD {}").format(sql.Identifier(role),sql.Literal(password)))
                connection.execute(sql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(sql.Identifier(self.schema),sql.Identifier(role)))
                connection.execute(sql.SQL("GRANT SELECT ON ALL TABLES IN SCHEMA {} TO {}").format(sql.Identifier(self.schema),sql.Identifier(role)))
            payload = {**self.payload,"connection_url":f"postgresql://{role}:{password}@127.0.0.1:{self.port}/postgres","allow_changes":True}
            session_id = workbench.start_postgres_session(self.account["account_id"],payload)["session_id"]
            self.assertEqual(len(workbench.submit_request(session_id,"show customers")["rows"]),2)
            rejected = workbench.submit_request(session_id,"INSERT INTO customers(name) VALUES ('forbidden')",raw_sql=True)
            self.assertFalse(rejected["matched"])
            self.assertIn("permission",rejected["message"])
        finally:
            with self.psycopg.connect(self.url) as connection:
                connection.execute(sql.SQL("DROP OWNED BY {}").format(sql.Identifier(role)))
                connection.execute(sql.SQL("DROP ROLE {}").format(sql.Identifier(role)))
