import { quoteIdentifier } from './api';

const types = {
  sqlite: ['TEXT', 'INTEGER', 'REAL', 'NUMERIC', 'BLOB'],
  postgresql: [
    'TEXT',
    'INTEGER',
    'BIGINT',
    'NUMERIC',
    'DOUBLE PRECISION',
    'BOOLEAN',
    'DATE',
    'TIMESTAMP',
    'TIMESTAMPTZ',
    'JSONB',
    'BYTEA',
  ],
};

export const schemaDialect = (session) =>
  [session.dialect, session.source, session.provider].includes('postgresql')
    ? 'postgresql'
    : 'sqlite';
export const schemaColumnTypes = (session) => types[schemaDialect(session)];

function newName(value, session) {
  const name = value.trim();
  if (!name || name.includes('\0')) throw new Error('Choose a name without null characters.');
  if (schemaDialect(session) === 'postgresql' && new TextEncoder().encode(name).length > 63)
    throw new Error('PostgreSQL names must be 63 bytes or fewer. Choose a shorter name.');
  return name;
}

const matchesName = (left, right) => left.toLowerCase() === right.toLowerCase();

// Only fixed SQL shapes and allowlisted types are accepted. All names are quoted as identifiers.
export function schemaStatement({
  action,
  name = '',
  type = 'TEXT',
  table,
  column,
  tables,
  session,
}) {
  const dialect = schemaDialect(session);
  if (session.read_only) throw new Error('This connection is read-only.');
  if (action === 'delete-table') return `DROP TABLE ${quoteIdentifier(table.name)}`;
  if (action === 'delete-column') {
    if (table.columns.length <= 1) throw new Error('Keep at least one column in the table.');
    if (dialect === 'sqlite' && column.primary_key)
      throw new Error('SQLite cannot delete a primary key column.');
    return `ALTER TABLE ${quoteIdentifier(table.name)} DROP COLUMN ${quoteIdentifier(column.name)}`;
  }
  const chosen = newName(name, session);
  if (['create-table', 'rename-table'].includes(action)) {
    if ((tables || []).some((item) => matchesName(item.name, chosen)))
      throw new Error('A table with this name already exists. Choose a different name.');
    if (action === 'create-table') {
      const key =
        dialect === 'postgresql'
          ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
          : 'INTEGER PRIMARY KEY';
      return `CREATE TABLE ${quoteIdentifier(chosen)} (${quoteIdentifier('id')} ${key})`;
    }
    return `ALTER TABLE ${quoteIdentifier(table.name)} RENAME TO ${quoteIdentifier(chosen)}`;
  }
  if ((table.columns || []).some((item) => matchesName(item.name, chosen)))
    throw new Error('A column with this name already exists. Choose a different name.');
  if (action === 'rename-column')
    return `ALTER TABLE ${quoteIdentifier(table.name)} RENAME COLUMN ${quoteIdentifier(column.name)} TO ${quoteIdentifier(chosen)}`;
  if (action === 'add-column') {
    if (!types[dialect].includes(type)) throw new Error('Choose an available column type.');
    return `ALTER TABLE ${quoteIdentifier(table.name)} ADD COLUMN ${quoteIdentifier(chosen)} ${type}`;
  }
  throw new Error('Choose a supported structure change.');
}
