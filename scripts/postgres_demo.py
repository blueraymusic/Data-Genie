"""Manage an isolated local PostgreSQL demo without touching existing databases."""

import argparse
import json
import os
from pathlib import Path
import secrets
import shlex
import shutil
import socket
import subprocess


ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "db" / "postgres-demo"


def binary(name):
    path = shutil.which(name)
    if not path:
        raise SystemExit(f"PostgreSQL's {name} is not on PATH. Install PostgreSQL first.")
    return path


def private_file(path, text):
    descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    with os.fdopen(descriptor, "w") as output:
        output.write(text)


def configuration(port):
    path = DIRECTORY / "settings.json"
    if path.is_file():
        return json.loads(path.read_text())
    if DIRECTORY.exists() and any(DIRECTORY.iterdir()):
        raise SystemExit("The demo directory already contains files. Nothing was overwritten.")
    with socket.socket() as probe:
        if probe.connect_ex(("127.0.0.1", port)) == 0:
            raise SystemExit(f"Port {port} is already in use. Choose another with --port.")
    DIRECTORY.mkdir(parents=True, mode=0o700, exist_ok=True)
    DIRECTORY.chmod(0o700)
    config = {"port": port, "admin_password": secrets.token_urlsafe(32),
              "password": secrets.token_urlsafe(24), "seeded": False}
    private_file(path, json.dumps(config))
    private_file(DIRECTORY / "admin-password", config["admin_password"])
    return config


def connect(config, admin=False, database=None):
    import psycopg
    return psycopg.connect(host="127.0.0.1", port=config["port"],
        user="genie_admin" if admin else "genie_demo",
        password=config["admin_password"] if admin else config["password"],
        dbname=database or ("postgres" if admin else "genie_demo"),
        sslmode="disable", connect_timeout=5, autocommit=admin)


def seed(config):
    from psycopg import sql
    with connect(config, admin=True) as admin:
        if not admin.execute("SELECT 1 FROM pg_roles WHERE rolname='genie_demo'").fetchone():
            admin.execute(sql.SQL("CREATE ROLE genie_demo LOGIN PASSWORD {}").format(sql.Literal(config["password"])))
        if not admin.execute("SELECT 1 FROM pg_database WHERE datname='genie_demo'").fetchone():
            admin.execute("CREATE DATABASE genie_demo OWNER genie_demo")
    with connect(config, admin=True, database="genie_demo") as admin:
        admin.execute("REVOKE CREATE ON SCHEMA public FROM PUBLIC")
        admin.execute("GRANT USAGE,CREATE ON SCHEMA public TO genie_demo")
    with connect(config) as connection:
        connection.execute("CREATE TABLE IF NOT EXISTS customers(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,email TEXT UNIQUE,state TEXT)")
        connection.execute("CREATE TABLE IF NOT EXISTS products(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,price NUMERIC(10,2) NOT NULL CHECK(price>=0))")
        connection.execute("CREATE TABLE IF NOT EXISTS orders(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,customer_id INTEGER REFERENCES customers(id),total NUMERIC(10,2),status TEXT,created_at DATE DEFAULT CURRENT_DATE)")
        if connection.execute("SELECT COUNT(*) FROM customers").fetchone()[0] == 0:
            with connection.cursor() as cursor:
                cursor.executemany("INSERT INTO customers(name,email,state) VALUES(%s,%s,%s)", [
                    ("Ana Brooks","ana@example.test","Illinois"),
                    ("Jon Reyes","jon@example.test","Missouri"),
                    ("Priya Nair","priya@example.test","Missouri"),
                    ("Avery Chen","avery@example.test","Iowa"),
                    ("Tom Whitaker","tom@example.test","Missouri")])
        if connection.execute("SELECT COUNT(*) FROM products").fetchone()[0] == 0:
            with connection.cursor() as cursor:
                cursor.executemany("INSERT INTO products(name,price) VALUES(%s,%s)", [
                    ("Notebook","12.50"),("Desk lamp","34.00"),("Travel mug","18.75")])
        if connection.execute("SELECT COUNT(*) FROM orders").fetchone()[0] == 0:
            connection.execute("INSERT INTO orders(customer_id,total,status) SELECT id,25.00,'shipped' FROM customers WHERE state='Missouri'")
            connection.execute("INSERT INTO orders(customer_id,total,status) SELECT id,49.50,'processing' FROM customers WHERE state='Iowa'")
        connection.execute("ANALYZE customers")
        connection.execute("ANALYZE products")
        connection.execute("ANALYZE orders")
    url = f"postgresql://genie_demo:{config['password']}@127.0.0.1:{config['port']}/genie_demo"
    if not (DIRECTORY / "connection.txt").exists():
        private_file(DIRECTORY / "connection.txt", url + "\n")
    config["seeded"] = True
    (DIRECTORY / "settings.json").write_text(json.dumps(config))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("start", "stop", "url"), nargs="?", default="start")
    parser.add_argument("--port", type=int, default=55432)
    arguments = parser.parse_args()
    if not 1 <= arguments.port <= 65535:
        parser.error("Choose a port between 1 and 65535.")
    if arguments.action == "url":
        path = DIRECTORY / "connection.txt"
        if not path.is_file():
            raise SystemExit("Start the demo first.")
        print(path.read_text().strip())
        return
    if arguments.action == "stop":
        if not (DIRECTORY / "data" / "PG_VERSION").is_file():
            raise SystemExit("No demo cluster has been created.")
        subprocess.run([binary("pg_ctl"), "-D", str(DIRECTORY / "data"), "-w", "stop", "-m", "fast"], check=True)
        return
    config = configuration(arguments.port)
    data = DIRECTORY / "data"
    if not (data / "PG_VERSION").is_file():
        subprocess.run([binary("initdb"), "-D", str(data), "-U", "genie_admin",
            "--auth-local=scram-sha-256", "--auth-host=scram-sha-256", "--pwfile", str(DIRECTORY / "admin-password"),
            "--no-locale", "--encoding=UTF8"], check=True, stdout=subprocess.DEVNULL)
    running = subprocess.run([binary("pg_ctl"), "-D", str(data), "status"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0
    if not running:
        options = f"-h 127.0.0.1 -p {config['port']} -k {shlex.quote(str(DIRECTORY))}"
        subprocess.run([binary("pg_ctl"), "-D", str(data), "-l", str(DIRECTORY / "server.log"), "-o", options, "-w", "start"], check=True)
    if not config["seeded"]:
        seed(config)
    print(f"Demo ready: 127.0.0.1:{config['port']} / genie_demo / public")
    print(f"Connection URL: {DIRECTORY / 'connection.txt'}")


if __name__ == "__main__":
    main()
